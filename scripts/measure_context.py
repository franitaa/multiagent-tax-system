"""Run the long session in both context modes and write docs/metrics.md.

  python -m scripts.measure_context [--turns 30] [--docs 12] [--out docs/metrics.md]

The scenario (src/scenarios.run_long_session) is identical in both modes: 30 user messages,
one graph call each, then 12 documents extracted in parallel, rules, computation, a review that
fails once, a revision, and a passing review. Only the context strategy differs.

Token counts are ESTIMATES (ceil(len(json)/4) of the view each agent was handed), because the
agents are stubs and no model reports real usage. They measure prompt size, not model cost.
"""
import argparse
import json
import tempfile
from pathlib import Path

from src.graph import build_graph
from src.scenarios import long_session_agents, run_long_session

DETERMINISTIC = {"orchestrator", "human"}  # plain code, not model calls
WIDTH = 40


def run_mode(scoped: bool, turns: int, n_docs: int, trace_dir: Path):
    thread_id = "scoped" if scoped else "full"
    graph = build_graph(trace_dir=trace_dir, context_strategy=scoped, agents=long_session_agents(turns))
    final = run_long_session(graph, thread_id, turns, n_docs)
    records = [json.loads(line) for line in (trace_dir / f"{thread_id}.jsonl").read_text().splitlines()]
    return final, records


def model_rows(records):
    """One row per model call; the parallel extraction workers are one row (mean per call)."""
    rows, seen = [], {}
    i = 0
    calls = [r for r in records if r["agent"] not in DETERMINISTIC]
    while i < len(calls):
        agent = calls[i]["agent"]
        if agent == "extraction":
            j = i
            while j < len(calls) and calls[j]["agent"] == "extraction":
                j += 1
            group = calls[i:j]
            rows.append((f"extraction x{len(group)} (mean per worker)", agent,
                         round(sum(c["input_tokens"] for c in group) / len(group)), len(group)))
            i = j
            continue
        seen[agent] = seen.get(agent, 0) + 1
        label = {"intake": f"intake turn {seen[agent]}"}.get(agent, f"{agent} #{seen[agent]}")
        if agent in ("computation", "review") and seen[agent] > 1:
            label += " (revision round)"
        rows.append((label, agent, calls[i]["input_tokens"], 1))
        i += 1
    return rows


def slope(values):
    """Least-squares tokens added per step."""
    n = len(values)
    mean_x, mean_y = (n - 1) / 2, sum(values) / n
    num = sum((x - mean_x) * (y - mean_y) for x, y in enumerate(values))
    den = sum((x - mean_x) ** 2 for x in range(n))
    return num / den


def bar(value, top):
    return "#" * max(1, round(WIDTH * value / top))


def build_markdown(turns, n_docs, scoped_rows, full_rows, scoped_rec, full_rec) -> str:
    assert [r[0] for r in scoped_rows] == [r[0] for r in full_rows], "modes ran different steps"
    pairs = list(zip(scoped_rows, full_rows))

    def total(rows):
        return sum(r[2] * r[3] for r in rows)

    s_total, f_total = total(scoped_rows), total(full_rows)
    intake = [(s[2], f[2]) for s, f in pairs if s[1] == "intake"]
    s_int, f_int = [a for a, _ in intake], [b for _, b in intake]
    top = max(f_int)
    doc_tokens = next(r[2] for r in scoped_rows if r[1] == "extraction") * n_docs

    out = [
        "# Context metrics",
        "",
        f"Generated by `python -m scripts.measure_context --turns {turns} --docs {n_docs}`. "
        "Do not edit by hand.",
        "",
        "**Read this first.** Token counts are **estimates**: `ceil(len(json)/4)` of the view each agent "
        "was handed. The agents are offline stubs, so no model reported real usage; the numbers measure "
        "prompt size, not model cost. The scenario is identical in both modes; only the context strategy "
        "changes (`--no-context-strategy` = every agent gets the full state).",
        "",
        f"**Scenario.** {turns} user messages (one graph call each), then {n_docs} documents of about 3 KB "
        "of fake text each extracted in parallel, rules, computation, a review that fails once, one "
        "revision round, and a passing review. Both modes ended in the same state "
        "(status, extracted records, computed lines and facts are identical).",
        "",
        "## Headline",
        "",
        "| | Strategy on (scoped) | Strategy off (full state) | Ratio |",
        "|---|---|---|---|",
        f"| Total input tokens, all model calls | {s_total:,} | {f_total:,} | {f_total / s_total:.1f}x |",
        f"| Intake input, turn 1 | {s_int[0]:,} | {f_int[0]:,} | |",
        f"| Intake input, turn {turns} | {s_int[-1]:,} | {f_int[-1]:,} | {f_int[-1] / s_int[-1]:.1f}x |",
        f"| Intake growth per turn (least squares) | {slope(s_int):.0f} tokens | {slope(f_int):.0f} tokens | "
        f"{slope(f_int) / slope(s_int):.1f}x |",
        "",
        "**How to read the ratios.** Most of the total and of the turn-1 gap is raw document text "
        f"(about {doc_tokens:,} tokens for {n_docs} documents, from the measured extraction worker view) that the full state carries into every call, "
        "so it is a property of this scenario (documents present from the start), not of conversation length. "
        "The fairer measure of curve *shape* is the growth per turn: the full state adds the whole new "
        "exchange each turn, the scoped view adds only the new fact.",
        "",
        "The scoped curve is flatter but **not flat**: every turn adds a structured fact (the stub stores one "
        "per answer) and Intake needs all facts so it does not re-ask. The chat window itself is capped at "
        "6 messages. A real Intake that records fewer, distinct facts would grow more slowly; retrieving only "
        "the facts relevant to the current question is the next step and is not built.",
        "",
        "## Intake input per turn (each # is about "
        f"{top / WIDTH:,.0f} tokens)",
        "",
        "```",
    ]
    for turn in sorted({1, 5, 10, 15, 20, 25, turns}):
        if turn <= len(s_int):
            out.append(f"turn {turn:>2}  on  {bar(s_int[turn - 1], top):<{WIDTH}} {s_int[turn - 1]:>6,}")
            out.append(f"         off {bar(f_int[turn - 1], top):<{WIDTH}} {f_int[turn - 1]:>6,}")
    out += ["```", "", "## Per agent (input tokens per call)", "",
            "| Agent | Calls | On: mean | On: max | Off: mean | Off: max | Mean ratio |", "|---|---|---|---|---|---|---|"]
    for agent in ("intake", "extraction", "rules", "computation", "review"):
        s_calls = [r["input_tokens"] for r in scoped_rec if r["agent"] == agent]
        f_calls = [r["input_tokens"] for r in full_rec if r["agent"] == agent]
        out.append(
            f"| {agent} | {len(s_calls)} | {sum(s_calls) // len(s_calls):,} | {max(s_calls):,} | "
            f"{sum(f_calls) // len(f_calls):,} | {max(f_calls):,} | "
            f"{(sum(f_calls) / len(f_calls)) / (sum(s_calls) / len(s_calls)):.1f}x |")

    def orch(rec):
        v = [r["input_tokens"] for r in rec if r["agent"] == "orchestrator"]
        return min(v), max(v)

    (s_lo, s_hi), (f_lo, f_hi) = orch(scoped_rec), orch(full_rec)
    out += [
        "",
        "## Orchestrator (deterministic code, not a model call)",
        "",
        f"View size per visit: **{s_lo} to {s_hi}** estimated tokens with the strategy on, "
        f"{f_lo:,} to {f_hi:,} with it off. With it on, the size does not depend on the number of turns or "
        "documents (bounded routing view; guard history and review findings travel on a separate control "
        "channel). Shown for completeness; it is excluded from the totals above.",
        "",
        "## Every step",
        "",
        "| # | Step | On (scoped) | Off (full state) | Ratio |",
        "|---|---|---|---|---|",
    ]
    for n, (s, f) in enumerate(pairs, 1):
        out.append(f"| {n} | {s[0]} | {s[2]:,} | {f[2]:,} | {f[2] / s[2]:.1f}x |")
    out.append("")
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--turns", type=int, default=30)
    parser.add_argument("--docs", type=int, default=12)
    parser.add_argument("--out", default="docs/metrics.md")
    args = parser.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        trace_dir = Path(tmp)
        scoped_final, scoped_rec = run_mode(True, args.turns, args.docs, trace_dir)
        full_final, full_rec = run_mode(False, args.turns, args.docs, trace_dir)

    for key in ("status", "extracted", "computed", "facts", "revision_count", "session_summary"):
        assert scoped_final[key] == full_final[key], f"modes disagree on {key}"

    markdown = build_markdown(args.turns, args.docs, model_rows(scoped_rec), model_rows(full_rec),
                              scoped_rec, full_rec)
    Path(args.out).write_text(markdown, encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
